function hexToRgb(hex) {
  const m = /^#?([0-9a-f]{6})$/i.exec(String(hex || ""));
  if (!m) return null;
  const n = parseInt(m[1], 16);
  return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255 };
}

// 将任意 hex 转换为最接近的中文颜色名
export function hexToChinese(hex) {
  const rgb = hexToRgb(hex);
  if (!rgb) return "";
  let best = null;
  let bestDist = Infinity;
  for (const entry of COLOR_DICTIONARY) {
    const ref = hexToRgb(entry.hex);
    if (!ref) continue;
    const dist = ((rgb.r - ref.r) ** 2) + ((rgb.g - ref.g) ** 2) + ((rgb.b - ref.b) ** 2);
    if (dist < bestDist) { bestDist = dist; best = entry; }
  }
  return best ? best.name : "";
}

// 同时返回中文名和 hex（用于 UI 展示）
export function colorLabel(hex) {
  const cn = hexToChinese(hex);
  return cn ? `${cn} ${hex}` : hex || "";
}

